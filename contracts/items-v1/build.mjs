import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import schema from './schema.json' with { type: 'json' };
import { assertDocument } from './validate.mjs';

const directory = new URL('./', import.meta.url);
const typeName = key => key[0].toUpperCase() + key.slice(1);
function typeOf(rule) {
  if (rule.$ref) return typeName(rule.$ref.slice(8));
  if ('const' in rule) return JSON.stringify(rule.const);
  if (rule.enum) return rule.enum.map(value => JSON.stringify(value)).join(' | ');
  if (Array.isArray(rule.type)) return rule.type.map(type => typeOf({ ...rule, type })).join(' | ');
  if (rule.type === 'object') return `{ ${Object.entries(rule.properties).map(([key, sub]) => `${JSON.stringify(key)}${rule.required?.includes(key) ? '' : '?'}: ${typeOf(sub)}`).join('; ')} }`;
  if (rule.type === 'array') return `Array<${typeOf(rule.items)}>`;
  return rule.type === 'integer' ? 'number' : rule.type;
}
const generated = {
  'types.d.ts': '// Generated from schema.json by build.mjs. Do not edit.\n' + Object.entries(schema.$defs).map(([key, rule]) => `export type ${typeName(key)} = ${typeOf(rule)};`).join('\n') + '\n',
  'validate.d.mts': '// Generated by build.mjs. Do not edit.\nimport type { Pointer, Manifest, Items } from "./types.d.ts";\nexport const FORMAT_VERSION: "items-v1";\nexport function assertDocument(kind: "pointer", value: unknown): Pointer;\nexport function assertDocument(kind: "manifest", value: unknown): Manifest;\nexport function assertDocument(kind: "items", value: unknown): Items;\nexport function canonicalJson(value: unknown): string;\nexport function releaseIdentity(manifest: Manifest): string;\n',
};
for (const [name, text] of Object.entries(generated)) {
  const target = new URL(name, directory);
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== text) throw new Error(`Generated contract drift: ${name}`);
  } else writeFileSync(target, text);
}
for (const kind of ['pointer', 'manifest', 'items']) {
  for (const invalid of [null, {}, [], { formatVersion: 'unsupported' }]) {
    let rejected = false;
    try { assertDocument(kind, invalid); } catch { rejected = true; }
    if (!rejected) throw new Error(`Invalid ${kind} accepted`);
  }
}
const files = ['schema.json', 'validate.mjs', 'validate.d.mts', 'types.d.ts', 'README.md', 'build.mjs'].sort();
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const inventory = files.map(name => `${hash(readFileSync(new URL(name, directory)))}  ${name}\n`).join('');
console.log(JSON.stringify({ formatVersion: 'items-v1', sha256: hash(inventory), files }));
